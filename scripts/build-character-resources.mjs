#!/usr/bin/env node
// Define virtual Doom sprites from an untouched generated sprite sheet.
// Cropping, size and foot alignment belong to TEXTURES; PNG bytes are copied as-is.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const artwork = resolve(root, 'art/intake-survivor-sheet.png');
const metadataPath = resolve(root, 'art/intake-survivor-sheet.json');
const patchPath = resolve(root, 'doom-mod/patches/intake-survivor-sheet.png');
const input = process.argv[2] ? resolve(process.argv[2]) : artwork;
const originalBytes = readFileSync(input);
const png = PNG.sync.read(originalBytes);
const columns = 8;
const rows = 4;
const targetHeight = 56;
const alphaThreshold = 128;
const views = ['front', 'front-left', 'left', 'rear-left', 'back', 'rear-right', 'right', 'front-right'];
const frames = [];

for (let row = 0; row < rows; row++) {
  for (let column = 0; column < columns; column++) {
    // Generated sheets need not have dimensions divisible by the grid size.
    const x = Math.round(column * png.width / columns);
    const y = Math.round(row * png.height / rows);
    const width = Math.round((column + 1) * png.width / columns) - x;
    const height = Math.round((row + 1) * png.height / rows) - y;
    let minX = width;
    let minY = height;
    let maxX = -1;
    let maxY = -1;
    let weightedTorsoX = 0;
    let torsoWeight = 0;
    for (let py = 0; py < height; py++) {
      for (let px = 0; px < width; px++) {
        const alpha = png.data[((y + py) * png.width + x + px) * 4 + 3];
        if (alpha < alphaThreshold) continue;
        minX = Math.min(minX, px);
        minY = Math.min(minY, py);
        maxX = Math.max(maxX, px);
        maxY = Math.max(maxY, py);
        // Center the pelvis/torso, so arm and foot swings do not drag the actor.
        if (py >= height * 0.4 && py < height * 0.6) {
          weightedTorsoX += px * alpha;
          torsoWeight += alpha;
        }
      }
    }
    if (maxX < 0 || torsoWeight === 0) throw new Error(`Missing character at row ${row + 1}, column ${column + 1}`);
    frames.push({
      name: `SURV${'ABCD'[row]}${column + 1}`,
      frame: 'ABCD'[row], rotation: column + 1, view: views[column],
      cell: { x, y, width, height },
      alphaBounds: { x: minX, y: minY, width: maxX - minX + 1, height: maxY - minY + 1 },
      offset: { x: Math.round(weightedTorsoX / torsoWeight), y: maxY + 1 },
    });
  }
}

const heights = frames.map(frame => frame.alphaBounds.height).sort((a, b) => a - b);
const medianHeight = (heights[15] + heights[16]) / 2;
// TEXTURES scaling is pixels per map unit: larger values render smaller.
const scale = Number((medianHeight / targetHeight).toFixed(6));
const definitions = [
  '// Generated by scripts/build-character-resources.mjs; source PNG remains unchanged.',
  '// Four walking phases, each with all eight Doom view rotations.',
  '// Per-frame pelvis centers and foot baselines prevent sheet-placement jitter.',
  '// Sprite naming/offsets: https://zdoom.org/wiki/Sprite',
  '// Parser: https://github.com/ZDoom/gzdoom/blob/master/src/common/textures/multipatchtexturebuilder.cpp',
  '',
  ...frames.map(frame => `Sprite "${frame.name}", ${frame.cell.width}, ${frame.cell.height}\n{\n    XScale ${scale}\n    YScale ${scale}\n    Offset ${frame.offset.x}, ${frame.offset.y}\n    Patch "patches/intake-survivor-sheet.png", ${-frame.cell.x}, ${-frame.cell.y}\n}\n`),
].join('\n');

mkdirSync(dirname(artwork), { recursive: true });
mkdirSync(dirname(patchPath), { recursive: true });
if (input !== artwork) copyFileSync(input, artwork);
copyFileSync(artwork, patchPath);
const previous = existsSync(metadataPath) ? JSON.parse(readFileSync(metadataPath, 'utf8')) : {};
const metadata = {
  ...previous,
  asset: 'intake-survivor',
  description: 'One stocky adult bearded survivor wearing gray shorts; provisional walking animation art.',
  generation: { tool: 'image_gen.imagegen', promptFile: 'art/intake-survivor-prompt.txt', ...previous.generation },
  source: { width: png.width, height: png.height, colorType: png.colorType, sha256: createHash('sha256').update(originalBytes).digest('hex') },
  grid: { columns, rows, rotations: views, phases: ['A', 'B', 'C', 'D'] },
  render: { spritePrefix: 'SURV', textureDefinitions: 'doom-mod/TEXTURES', patch: 'patches/intake-survivor-sheet.png', targetHeight, pixelsPerMapUnit: scale, alphaThreshold, sourcePixelsModified: false },
  limitations: previous.limitations ?? [
    'One adult character repeated for the first integration test; crowd variety is not yet authored.',
    'Only standing/walking phases are supplied; pain, death, handover and armed poses are not generated.',
    'AI-generated poses need in-engine review for silhouette consistency, transparency fringes and foot sliding.',
  ],
  frames,
};
writeFileSync(resolve(root, 'doom-mod/TEXTURES'), definitions);
writeFileSync(metadataPath, `${JSON.stringify(metadata, null, 2)}\n`);
const copiedHash = createHash('sha256').update(readFileSync(patchPath)).digest('hex');
if (copiedHash !== metadata.source.sha256) throw new Error('Copied patch differs from original source');
console.log(`Defined ${frames.length} SURV sprites from ${png.width}x${png.height} unmodified RGBA pixels at ${scale} px/map-unit.`);
console.log(`Source SHA-256: ${metadata.source.sha256}`);
